"""Repository policy: no tool-generated attribution anywhere.

Rejects "Generated by/with ..." footers, session-link trailers and
Co-authored-by trailers in commit messages, and the same footers in tracked
files. Run in CI and, optionally, as a local commit-msg hook:

    git config core.hooksPath .githooks

Usage:
    python tools/check_attribution.py --commits         # every commit on HEAD
    python tools/check_attribution.py --files           # tracked files
    python tools/check_attribution.py --message FILE    # one commit message
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

MESSAGE_RULES = [
    (re.compile(r"(?im)^\s*co-authored-by:"), "Co-authored-by trailer"),
    (re.compile(r"(?im)^\s*[\w-]*-session:\s*https?://"), "session link trailer"),
    (re.compile(r"(?im)^\W*generated (by|with)\b"), "'Generated by/with' footer"),
]
FILE_RULES = [
    (re.compile(r"(?im)^\W*generated (by|with) \[?[A-Z][\w ]*\]?\(https?://"),
     "'Generated by/with' footer"),
    (re.compile(r"(?im)^\s*co-authored-by:"), "Co-authored-by trailer"),
    (re.compile(r"(?im)^\s*[\w-]*-session:\s*https?://"), "session link trailer"),
]
SKIP = {"tools/check_attribution.py"}
TEXT_SUFFIXES = {".py", ".md", ".txt", ".toml", ".yml", ".yaml", ".spec", ".in", ".cfg",
                 ".ini", ".json", ".ps1", ".sh", ""}


def check_message(text: str) -> list[str]:
    return [why for rx, why in MESSAGE_RULES if rx.search(text)]


def check_commits() -> list[str]:
    out = subprocess.run(["git", "log", "--format=%H%x00%B%x1e", "HEAD"],
                         capture_output=True, text=True, check=True).stdout
    problems = []
    for entry in out.split("\x1e"):
        if "\x00" not in entry:
            continue
        sha, body = entry.strip().split("\x00", 1)
        for why in check_message(body):
            problems.append(f"commit {sha[:7]}: {why}")
    return problems


def check_files() -> list[str]:
    files = subprocess.run(["git", "ls-files"], capture_output=True, text=True,
                           check=True).stdout.splitlines()
    problems = []
    for name in files:
        if name in SKIP or Path(name).suffix.lower() not in TEXT_SUFFIXES:
            continue
        try:
            text = Path(name).read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        for rx, why in FILE_RULES:
            for m in rx.finditer(text):
                line = text.count("\n", 0, m.start()) + 1
                problems.append(f"{name}:{line}: {why}")
    return problems


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--commits", action="store_true")
    ap.add_argument("--files", action="store_true")
    ap.add_argument("--message", metavar="FILE")
    args = ap.parse_args()
    problems: list[str] = []
    if args.message:
        problems += [f"commit message: {w}" for w in
                     check_message(Path(args.message).read_text(encoding="utf-8"))]
    if args.commits:
        problems += check_commits()
    if args.files:
        problems += check_files()
    for p in problems:
        print(f"::error::{p}" if "GITHUB_ACTIONS" in __import__("os").environ else p)
    if problems:
        print("Attribution text is not allowed in this repository. See CONTRIBUTING.md.")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
