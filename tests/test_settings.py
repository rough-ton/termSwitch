def test_powerline_setting_and_system_scheme_in_the_window(qapp, tmp_path, monkeypatch):
    from termswitch import ui
    from termswitch.config_store import ProfileStore
    from termswitch.terminal_widget import TerminalWidget
    cfg = tmp_path / "config"
    cfg.write_text("[profile a]\nregion = us-west-2\n", encoding="utf-8")
    settings = QSettings(str(tmp_path / "ui.ini"), QSettings.Format.IniFormat)
    settings.setValue("check_on_startup", False)
    settings.setValue("term_powerline", False)
    settings.setValue("term_scheme", st.MATCH_SYSTEM)
    monkeypatch.setattr(ui.MainWindow, "run_dependency_check", lambda *a, **k: None)
    calls = []

    def fake_read(platform, dark, choice="auto", **kw):
        calls.append(dark)
        return st.SystemScheme("iTerm2", ts.BUILTIN["Gruvbox Dark"], "default profile 'x'")
    monkeypatch.setattr(ui, "read_system_scheme", fake_read)
    w = ui.MainWindow(store=ProfileStore(cfg, tmp_path / "credentials"), settings=settings)
    try:
        assert TerminalWidget.draw_powerline is False
        assert w._scheme_for(w.store.profiles["a"]).name == "Gruvbox Dark"
        w._scheme_for(None)
        assert len(calls) == 1                       # read once, then cached
        w.theme.apply("dark")
        w._scheme_for(None)
        assert len(calls) == 2                       # read again after a theme change
        monkeypatch.setattr(ui, "read_system_scheme",
                            lambda *a, **k: st.SystemScheme("iTerm2", None, "nope"))
        w._system_cache = None
        assert w._scheme_for(None).name in ("Dark", "Light")    # falls back
    finally:
        settings.setValue("term_powerline", True)
        w._apply_terminal_settings()
        w.theme.apply("light")
        w.close()
        w.deleteLater()
    assert TerminalWidget.draw_powerline is True


