def test_import_and_remove_a_scheme(dialog, tmp_path, monkeypatch):
    from PySide6.QtWidgets import QFileDialog
    src = tmp_path / "mine.json"
    src.write_text(json.dumps({"name": "Mine", "foreground": "#ffffff", "background": "#000000",
                               **{k: "#123456" for k in ts._WT_KEYS}}), encoding="utf-8")
    monkeypatch.setattr(QFileDialog, "getOpenFileName", lambda *a, **k: (str(src), ""))
    monkeypatch.setattr(QMessageBox, "information", lambda *a, **k: None)
    dialog._import_scheme()
    assert dialog.term_scheme.currentData() == "Mine"
    assert "(imported)" in dialog.term_scheme.currentText()
    assert dialog.remove_btn.isEnabled()
    monkeypatch.setattr(QMessageBox, "question",
                        lambda *a, **k: QMessageBox.StandardButton.Yes)
    dialog._remove_scheme()
    assert "Mine" not in dialog.schemes
    assert dialog.term_scheme.currentData() == ts.MATCH_APP
    assert not list((tmp_path / "schemes").glob("*.json"))
    # Built-in schemes can't be removed.
    dialog.term_scheme.setCurrentIndex(dialog.term_scheme.findData("Dracula"))
    assert not dialog.remove_btn.isEnabled()
    with pytest.raises(ts.SchemeError):
        ts.delete_user_scheme("Dracula", tmp_path / "schemes")


