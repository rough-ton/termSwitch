def iterm_color(hex_color: str) -> dict:
    r, g, b = (int(hex_color[i:i + 2], 16) / 255 for i in (1, 3, 5))
    return {"Red Component": r, "Green Component": g, "Blue Component": b,
            "Color Space": "sRGB"}


def write_iterm(home: Path, separate: bool = False):
    profile = {"Guid": "abc", "Name": "Work",
               "Foreground Color": iterm_color("#eeeeee"),
               "Background Color": iterm_color("#111111"),
               **{f"Ansi {i} Color": iterm_color(f"#{i:02x}{i:02x}{i:02x}") for i in range(16)}}
    if separate:
        profile["Use Separate Colors for Light and Dark Mode"] = True
        profile["Background Color (Light)"] = iterm_color("#fafafa")
        profile["Background Color (Dark)"] = iterm_color("#050505")
    prefs = home / "Library" / "Preferences"
    prefs.mkdir(parents=True, exist_ok=True)
    data = {"Default Bookmark Guid": "abc",
            "New Bookmarks": [{"Guid": "other", "Name": "Other"}, profile]}
    (prefs / "com.googlecode.iterm2.plist").write_bytes(
        plistlib.dumps(data, fmt=plistlib.FMT_BINARY))


def archived(hex_color: str) -> bytes:
    """An NSColor as Terminal.app stores it (NSKeyedArchiver)."""
    r, g, b = (int(hex_color[i:i + 2], 16) / 255 for i in (1, 3, 5))
    archive = {"$archiver": "NSKeyedArchiver", "$version": 100000,
               "$top": {"root": plistlib.UID(1)},
               "$objects": ["$null",
                            {"NSColorSpace": 2, "NSRGB": f"{r:.6f} {g:.6f} {b:.6f}\x00".encode(),
                             "$class": plistlib.UID(2)},
                            {"$classname": "NSColor", "$classes": ["NSColor", "NSObject"]}]}
    return plistlib.dumps(archive, fmt=plistlib.FMT_BINARY)


def write_terminal_app(home: Path, with_ansi: bool = True):
    profile = {"TextColor": archived("#d0d0d0"), "BackgroundColor": archived("#1a1a1a")}
    if with_ansi:
        for i, base in enumerate(st._TERMINAL_APP_KEYS * 2):
            profile[f"ANSI{'Bright' if i >= 8 else ''}{base}Color"] = archived(
                f"#{i * 10:02x}0000")
    prefs = home / "Library" / "Preferences"
    prefs.mkdir(parents=True, exist_ok=True)
    data = {"Default Window Settings": "Clear Dark", "Window Settings": {"Clear Dark": profile}}
    (prefs / "com.apple.Terminal.plist").write_bytes(plistlib.dumps(data, fmt=plistlib.FMT_BINARY))


def test_iterm2_default_profile(tmp_path):
    write_iterm(tmp_path)
    found = st.read_system_scheme("darwin", True, "auto", home=tmp_path)
    assert found.source == "iTerm2" and "Work" in found.detail
    assert found.scheme.background == "#111111" and found.scheme.ansi[15] == "#0f0f0f"


def test_iterm2_separate_light_and_dark_colors(tmp_path):
    write_iterm(tmp_path, separate=True)
    assert st.read_system_scheme("darwin", True, "iterm", home=tmp_path).scheme.background \
        == "#050505"
    assert st.read_system_scheme("darwin", False, "iterm", home=tmp_path).scheme.background \
        == "#fafafa"


def test_terminal_app_profile(tmp_path):
    write_terminal_app(tmp_path)
    write_iterm(tmp_path)            # installed, but the external terminal is Terminal.app
    found = st.read_system_scheme("darwin", True, "terminal", home=tmp_path)
    assert found.source == "Terminal.app" and "Clear Dark" in found.detail
    assert found.scheme.foreground == "#d0d0d0" and found.scheme.background == "#1a1a1a"
    assert found.scheme.ansi[1] == "#0a0000"


def test_terminal_app_missing_ansi_colors_use_defaults(tmp_path):
    write_terminal_app(tmp_path, with_ansi=False)
    found = st.read_system_scheme("darwin", True, "terminal", home=tmp_path)
    assert found.scheme.background == "#1a1a1a"
    assert found.scheme.ansi == ts.BUILTIN["Dark"].ansi


def test_reading_never_changes_the_files(tmp_path):
    write_iterm(tmp_path)
    write_terminal_app(tmp_path)
    env = wt_env(tmp_path)
    files = [p for p in tmp_path.rglob("*") if p.is_file()]
    before = {p: (p.read_bytes(), p.stat().st_mtime_ns) for p in files}
    st.read_system_scheme("darwin", True, "auto", home=tmp_path)
    st.read_system_scheme("darwin", False, "terminal", home=tmp_path)
    st.read_system_scheme("win32", True, env=env)
    assert {p: (p.read_bytes(), p.stat().st_mtime_ns) for p in files} == before


def test_oversized_files_are_refused(tmp_path, monkeypatch):
    monkeypatch.setattr(st, "MAX_BYTES", 10)
    found = st.read_system_scheme("win32", True, env=wt_env(tmp_path))
    assert found.scheme is None and "too large" in found.detail


