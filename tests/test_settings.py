def test_unknown_or_broken_settings_never_raise(tmp_path):
    missing = st.read_system_scheme(
        "win32", True, env=wt_env(tmp_path / "a", '{"profiles": {"defaults": '
                                                  '{"colorScheme": "Nope"}, "list": []}}'))
